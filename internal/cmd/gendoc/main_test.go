package main

import (
	"errors"
	"os"
	"strings"
	"testing"

	"fillmore-labs.com/errortype/internal/gendoc"
)

func TestRun(t *testing.T) {
	const foreign = "package example\n"

	tests := [...]struct {
		name, existing string
		wantErr        error
		wantContent    string
	}{
		{"new", "", nil, "errorname reports examples."},
		{"generated", "// Code generated by gendoc; DO NOT EDIT.\n\npackage main\n", nil, "errorname reports examples."},
		{"not generated", foreign, gendoc.ErrNotGenerated, foreign},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Chdir(t.TempDir())

			if err := os.Mkdir("analyzer", 0o700); err != nil {
				t.Fatal(err)
			}

			if tt.existing != "" {
				if err := os.WriteFile("doc.go", []byte(tt.existing), 0o600); err != nil {
					t.Fatal(err)
				}
			}

			t.Chdir("analyzer")

			if err := os.WriteFile("doc.txt", []byte("reports examples\n"), 0o600); err != nil {
				t.Fatal(err)
			}

			if err := run("errorname"); !errors.Is(err, tt.wantErr) {
				t.Fatalf("run() = %v, want %v", err, tt.wantErr)
			}

			content, err := os.ReadFile("../doc.go")
			if err != nil {
				t.Fatal(err)
			}

			if !strings.Contains(string(content), tt.wantContent) {
				t.Errorf("doc.go = %q, want it to contain %q", content, tt.wantContent)
			}
		})
	}
}
