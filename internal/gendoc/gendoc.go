// Package gendoc generates the documentation of an analyzer command from the
// analyzer documentation.
//
// The analyzer documentation is the text file [SourceFile] in the analyzer package,
// embedded as [golang.org/x/tools/go/analysis.Analyzer.Doc]. It starts with a
// single-line summary, a brief verb phrase, followed by a blank line and the
// description. The description may end with sections introduced by headings
// (e.g., "# Examples").
//
// [Generate] produces the [CommandFile] of the command: the summary, usage,
// description, the flags of the analyzer and of the analysis driver, and the
// remaining sections. Driver flags are documented from a positive list
// (-c, -diff, -fix, -test).
//
// The analyzer package is a direct subdirectory of its command, so both can be
// moved together.
package gendoc

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
)

// File names, relative to the analyzer package.
const (
	SourceFile  = "doc.txt"   // the analyzer documentation
	CommandFile = "../doc.go" // the generated command documentation
)

// ErrNotGenerated is returned by [ReadCommandFile] when the file is not generated.
var ErrNotGenerated = errors.New("not generated by gendoc")

// Generate generates the documentation of the named command from doc, the analyzer
// documentation, listing the analyzer's flags.
func Generate(name, doc string, flags *flag.FlagSet) ([]byte, error) {
	sections, err := splitDoc(doc)
	if err != nil {
		return nil, err
	}

	flagList, err := renderFlags(flags)
	if err != nil {
		return nil, err
	}

	return renderCommand(name, sections, flagList)
}

// ReadCommandFile reads [CommandFile] relative to the current directory, the analyzer package.
//
// It returns [ErrNotGenerated] when the file is not generated, so it belongs to something else.
func ReadCommandFile() ([]byte, error) {
	content, err := os.ReadFile(CommandFile)
	if err != nil {
		return nil, err
	}

	if !bytes.HasPrefix(content, []byte(header)) {
		return nil, fmt.Errorf("%s: %w", CommandFile, ErrNotGenerated)
	}

	return content, nil
}
