package gendoc

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"strings"
)

const header = "// Code generated by gendoc; DO NOT EDIT.\n\n"

var errCommentEnd = errors.New(`documentation contains "*/"`)

// renderCommand renders the doc.go of the command.
func renderCommand(name string, d docSections, flags string) ([]byte, error) {
	for _, s := range [...]string{d.Summary, d.Body, d.Rest, flags} {
		if strings.Contains(s, "*/") {
			return nil, errCommentEnd
		}
	}

	var buf bytes.Buffer

	buf.WriteString(header)
	buf.WriteString("/*\n")
	fmt.Fprintf(&buf, "%s %s.\n\n", name, d.Summary)
	fmt.Fprintf(&buf, "Usage:\n\n\t%s [flags] [packages]\n\n", name)

	if d.Body != "" {
		fmt.Fprintf(&buf, "%s\n\n", d.Body)
	}

	fmt.Fprintf(&buf, "The flags are:\n\n%s\n", flags)

	if d.Rest != "" {
		fmt.Fprintf(&buf, "\n%s\n", d.Rest)
	}

	buf.WriteString("*/\npackage main\n")

	return format.Source(buf.Bytes())
}
