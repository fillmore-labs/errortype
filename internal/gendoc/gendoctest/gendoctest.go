// Package gendoctest checks that the command documentation generated by [gendoc] is up to date.
package gendoctest

import (
	"errors"
	"fmt"
	"strings"

	"github.com/google/go-cmp/cmp"
	"golang.org/x/tools/go/analysis"

	"fillmore-labs.com/errortype/internal/gendoc"
)

// ErrOutOfDate is returned by [CheckUpToDate] when the generated command
// documentation differs from what [gendoc.Generate] produces.
var ErrOutOfDate = errors.New(`documentation is out of date, run "go generate"`)

// CheckUpToDate returns [ErrOutOfDate], including the differences, when the command
// documentation of the analyzer differs from what [gendoc.Generate] produces.
//
// It must be called from a test in the analyzer package.
func CheckUpToDate(a *analysis.Analyzer) error {
	want, err := gendoc.Generate(a.Name, a.Doc, &a.Flags)
	if err != nil {
		return err
	}

	got, err := gendoc.ReadCommandFile()
	if err != nil {
		return err
	}

	// Compare lines, cmp.Diff cuts strings at arbitrary positions.
	if diff := cmp.Diff(strings.Split(string(got), "\n"), strings.Split(string(want), "\n")); diff != "" {
		return fmt.Errorf("%s: %w (-file +generated):\n%s", gendoc.CommandFile, ErrOutOfDate, diff)
	}

	return nil
}
